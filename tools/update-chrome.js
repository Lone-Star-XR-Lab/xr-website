#!/usr/bin/env node
/*
 * Copies the real lonestar.edu header (navbar, search, "Ask" modal) and footer
 * ("Make LSC part of your story" band + footer) out of reference/live-page.html into
 * preview/site-chrome.js, which the preview pages load. PREVIEW ONLY: none of this
 * goes into the CMS.
 *
 *   node tools/update-chrome.js          use the saved snapshot
 *   node tools/update-chrome.js --live   download a fresh snapshot first
 *
 * Re-run with --live if the college changes its header or footer.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SNAPSHOT = path.join(ROOT, "reference/live-page.html");
const OUT = path.join(ROOT, "preview/site-chrome.js");
const LIVE_URL = "https://www.lonestar.edu/Tomball-XR-Lab";

function between(html, start, end, { inclusive = true } = {}) {
  const a = html.indexOf(start);
  if (a < 0) throw new Error(`Couldn't find "${start}" in the snapshot; the template may have changed.`);
  const b = html.indexOf(end, a + start.length);
  if (b < 0) throw new Error(`Couldn't find "${end}" after "${start}".`);
  return inclusive ? html.slice(a, b + end.length) : html.slice(a + start.length, b);
}

function clean(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, (s) =>
      // Keep the copyright year; drop every other script (search scripts load separately).
      /getFullYear/.test(s) ? String(new Date().getFullYear()) : "")
    .replace(/<link[^>]*addsearch[^>]*>/gi, "")
    .replace(/(href|src|action)="\/\//g, '$1="https://')
    .replace(/(href|src|action)="\/(?!\/)/g, '$1="https://www.lonestar.edu/')
    .replace(/[^\x00-\x7e]/g, (c) => `&#${c.codePointAt(0)};`)
    .replace(/\r\n/g, "\n")
    .replace(/\n\s*\n+/g, "\n");
}

async function main() {
  if (process.argv.includes("--live") || !fs.existsSync(SNAPSHOT)) {
    console.log(`Downloading ${LIVE_URL} ...`);
    const res = await fetch(LIVE_URL, { headers: { "User-Agent": "Mozilla/5.0 (xr-website preview)" } });
    fs.mkdirSync(path.dirname(SNAPSHOT), { recursive: true });
    fs.writeFileSync(SNAPSHOT, Buffer.from(await res.arrayBuffer()));
  }
  const html = new TextDecoder("windows-1252").decode(fs.readFileSync(SNAPSHOT));

  const skip = between(html, "<!--Begin Accessibility-->", "<!--End Accessibility-->", { inclusive: false })
    .replace(/<!--Begin Accessibility-->/g, "");
  const header = between(html, '<header id="header"', "</header>");
  const modalStart = '<div class="modal fade" id="addsearch-popup"';
  const modal = modalStart + between(html, modalStart, "<!-- end header -->", { inclusive: false });
  const story = between(html, '<section class="story-section', "</section>");
  const footer = between(html, '<footer class="footer"', "</footer>");

  const parts = {
    header: clean(skip + "\n" + header + "\n" + modal),
    footer: clean(story + "\n" + footer),
  };

  const js = `/* GENERATED by tools/update-chrome.js from reference/live-page.html (${new Date().toISOString().slice(0, 10)}).
 * Do not edit by hand. PREVIEW ONLY: the real site header and footer, so the
 * preview pages show the full lonestar.edu look. Add ?bare to the address to hide them.
 */
(function () {
  var parts = ${JSON.stringify(parts, null, 2)};
  var bare = /[?&]bare\\b/.test(location.search);
  window.LSCPreview = {
    header: function () { if (!bare) document.write(parts.header); },
    footer: function () { if (!bare) document.write(parts.footer); }
  };
})();
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, js);
  console.log(`Wrote ${path.relative(ROOT, OUT)} (header ${parts.header.length} chars, footer ${parts.footer.length} chars)`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
